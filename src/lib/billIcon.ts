export function billIcon(title: string) {
  const n = ` ${normalizeName(title)} `
  let best = { icon: '💶', len: 0 }
  for (const [kw, icon] of ICONS) {
    const re = new RegExp(`[^a-z]${kw.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}s?[^a-z]`)
    if (kw.length > best.len && re.test(n)) best = { icon, len: kw.length }
  }
  return best.icon
}
